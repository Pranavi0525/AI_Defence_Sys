#!/usr/bin/env python3
"""
scripts/v2_stealth_sweep.py -- how does detection degrade as a growing share of attackers ADAPT to look legitimate?

stealth = probability an individual attacker removes the features that gave its family away (see v2/gen.py).
Everything else (legit mix, onboarding share, young accounts) is held at the 'hard' setting.
Reported per stealth level: grouped-CV F1 / recall (all features and behaviour-only), per-family recall, and the
strongest single-feature AUC per family (a family with a single feature AUC > ~0.95 is separable by one column).

    PowerShell: $env:PYTHONPATH="src"; python scripts/v2_stealth_sweep.py
"""
import json, sys, warnings
from pathlib import Path
warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "src"))
import numpy as np, pandas as pd
from sklearn.metrics import roc_auc_score
from v2 import phases as P
from v2.evalkit import BEHAVIOUR, FAMILIES_V2, basic_metrics, folds_for, oof_xgb
from v2.features import build_world_b

LEVELS = [0.0, 0.25, 0.5, 0.75, 1.0]
HARD = dict(onboarding_share=0.20, young_share=0.12)


def max_single_feature_auc(B, fam):
    sub = pd.concat([B[B.fraud == 0], B[B.family == fam]])
    best = (None, 0.5)
    for c in P.FEATS_B:
        x = sub[c].fillna(-999)
        if x.nunique() > 1:
            a = roc_auc_score(sub.fraud, x)
            if abs(a - 0.5) > abs(best[1] - 0.5):
                best = (c, a)
    return best


def main():
    rows = []
    for st in LEVELS:
        B = build_world_b(stealth=st, **HARD)
        y = B.fraud.values
        r = {"stealth": st, "n": len(B)}
        for name, feats in [("all_features", P.FEATS_B), ("behaviour_only", BEHAVIOUR)]:
            ps = [oof_xgb(B, feats, folds_for(B, s)) for s in P.SEEDS]
            ms = [basic_metrics(y, p) for p in ps]
            r[name] = {k: float(np.mean([m[k] for m in ms])) for k in ("f1", "recall", "precision", "fp", "fn")}
            if name == "all_features":
                r["per_family_recall"] = {f: float(np.mean([(p[(B.family == f).values] >= 0.5).mean() for p in ps])) for f in FAMILIES_V2}
        r["max_single_feature_auc"] = {f: dict(zip(("feature", "auc"), max_single_feature_auc(B, f))) for f in FAMILIES_V2}
        rows.append(r)
        print(f"stealth {st:.2f}: all-features F1 {r['all_features']['f1']:.3f} | behaviour-only F1 {r['behaviour_only']['f1']:.3f}", flush=True)
    out = ROOT / "reports" / "v2"
    out.mkdir(parents=True, exist_ok=True)
    (out / "stealth_sweep.json").write_text(json.dumps(rows, indent=2, default=float), encoding="utf-8")
    L = ["# Stealth sweep (generated by scripts/v2_stealth_sweep.py)", "",
         "Share of attackers that adapt to look legitimate, vs grouped-CV performance (mean of 3 fold seeds). SYNTHETIC data.", "",
         "| stealth | F1 all features | recall | FP | FN | F1 behaviour-only | " + " | ".join(f"recall {f}" for f in FAMILIES_V2) + " |",
         "|---|---|---|---|---|---|" + "---|" * 4]
    for r in rows:
        a = r["all_features"]
        L.append(f"| {r['stealth']:.2f} | {a['f1']:.3f} | {a['recall']:.3f} | {a['fp']:.1f} | {a['fn']:.1f} | {r['behaviour_only']['f1']:.3f} | "
                 + " | ".join(f"{r['per_family_recall'][f]:.3f}" for f in FAMILIES_V2) + " |")
    L += ["", "Strongest single-feature AUC per family (distance from 0.5 matters):", "| stealth | " + " | ".join(FAMILIES_V2) + " |", "|---|" + "---|" * 4]
    for r in rows:
        L.append(f"| {r['stealth']:.2f} | " + " | ".join(f"{r['max_single_feature_auc'][f]['feature']} {r['max_single_feature_auc'][f]['auc']:.2f}" for f in FAMILIES_V2) + " |")
    (out / "stealth_sweep.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
