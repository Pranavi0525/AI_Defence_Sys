#!/usr/bin/env python3
"""
scripts/run_phase8_public_check.py -- Phase 8: method check of the Stage 2 recipe on the public ULB credit-card fraud dataset.

Get the data (you must do this yourself; it needs a free Kaggle account):
    https://www.kaggle.com/datasets/mlg-ulb/creditcardfraud   -> download creditcard.csv -> put it at  data\\public\\creditcard.csv
    (the file is large and is NOT committed to git: add  data/public/  to .gitignore)

Run (cmd), one stage at a time; each should finish in a few minutes:
    set PYTHONPATH=src
    python scripts\\run_phase8_public_check.py --stage main
    python scripts\\run_phase8_public_check.py --stage control
    python scripts\\run_phase8_public_check.py --stage rolling
    python scripts\\run_phase8_public_check.py --stage report
Options: --csv PATH (default data\\public\\creditcard.csv), --boot 200, --seed 42.
Writes reports/public/phase8_<stage>.json and, for --stage report, reports/public/phase8_report.md. Every number comes from these runs.
"""
import argparse, json, sys, time, warnings
from pathlib import Path
warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "src"))

import numpy as np  # noqa: E402
from v2 import public_check as pc  # noqa: E402

OUT = ROOT / "reports" / "public"      # overridden by --out (used for dry runs on stand-in data)


def load(args):
    df, notes = pc.load_creditcard(args.csv)
    return df, pc.make_X(df), df["Class"].values.astype(int), notes


def save(stage, doc):
    OUT.mkdir(parents=True, exist_ok=True)
    p = OUT / f"phase8_{stage}.json"
    p.write_text(json.dumps(doc, indent=1), encoding="utf-8")
    print("wrote", p)


def stage_main(args):
    t0 = time.time()
    df, X, y, notes = load(args)
    doc = {"data": {"rows": int(len(df)), "fraud": int(y.sum()), "prevalence": float(y.mean()), "time_range_s": [float(df.Time.min()), float(df.Time.max())], "notes": notes},
           "seed": args.seed, "split_fractions": list(pc.SPLIT),
           "time_split": pc.evaluate_split(X, y, pc.time_split(len(y)), args.seed, args.boot),
           "random_split": pc.evaluate_split(X, y, pc.random_split(y, args.seed), args.seed, args.boot)}
    save("main", doc)
    print(f"done in {time.time() - t0:.0f}s")


def stage_control(args):
    t0 = time.time()
    _, X, y, _ = load(args)
    save("control", {"label_shuffle_time_split": pc.label_shuffle_control(X, y, pc.time_split(len(y)), args.seed)})
    print(f"done in {time.time() - t0:.0f}s")


def stage_rolling(args):
    t0 = time.time()
    _, X, y, _ = load(args)
    save("rolling", {"rolling_origin": pc.rolling_origin(X, y, 6, args.seed)})
    print(f"done in {time.time() - t0:.0f}s")


def ci(v):
    return f"[{v[0]:.3f}, {v[1]:.3f}]"


def stage_report(_):
    parts = {s: json.loads((OUT / f"phase8_{s}.json").read_text(encoding="utf-8")) for s in ("main", "control", "rolling") if (OUT / f"phase8_{s}.json").exists()}
    if "main" not in parts:
        sys.exit("run --stage main first")
    M = parts["main"]
    d = M["data"]
    L = ["# Phase 8: method check on a public dataset (generated by scripts/run_phase8_public_check.py)", "",
         "**This is a check of the modelling METHOD, not of the AI Defence System.** The public data has no sessions, devices, payees or graph.", "",
         f"Data: {d['rows']:,} transactions, {d['fraud']} frauds (prevalence {d['prevalence']:.4%}), time range {d['time_range_s'][0]:.0f}-{d['time_range_s'][1]:.0f} s (about {d['time_range_s'][1] / 3600:.0f} hours). "
         f"Split {M['split_fractions']} = train / validation (used only for calibration) / test. Seed {M['seed']}. Raw `Time` is not a feature."]
    L += [f"- NOTE: {n}" for n in d["notes"]]
    for split in ("time_split", "random_split"):
        S = M[split]
        L += ["", f"## {split.replace('_', ' ')} (test: {S['sizes']['test']:,} rows, {S['fraud']['test']} frauds; train frauds {S['fraud']['train']}, validation frauds {S['fraud']['validation']})", "",
              "| model | calibration | average precision | ROC AUC | Brier | ECE | recall @0.1% alerts | recall @0.5% alerts | precision @0.5% alerts | recall @1% alerts |", "|---|---|---|---|---|---|---|---|---|---|"]
        for model, R in S["models"].items():
            for cal, m in R.items():
                L.append(f"| {model} | {cal} | {m['average_precision']:.3f} | {m['roc_auc']:.3f} | {m['brier']:.5f} | {m['ece_10_quantile_bins']:.5f} | "
                         f"{m['recall_at_0.1pct_alerts']:.3f} | {m['recall_at_0.5pct_alerts']:.3f} | {m['precision_at_0.5pct_alerts']:.3f} | {m['recall_at_1pct_alerts']:.3f} |")
        x = S["models"]["xgboost"]["raw"]
        L += ["", f"XGBoost raw, bootstrap 95% over test rows: average precision {ci(x['average_precision_ci95'])}, recall @0.5% alerts {ci(x['recall_at_0.5pct_alerts_ci95'])}."]
    t, r = M["time_split"]["models"]["xgboost"]["raw"], M["random_split"]["models"]["xgboost"]["raw"]
    L += ["", "## Time split vs random split (XGBoost raw)", "",
          f"Average precision: time {t['average_precision']:.3f} vs random {r['average_precision']:.3f} (difference {r['average_precision'] - t['average_precision']:+.3f}); "
          f"recall @0.5% alerts: time {t['recall_at_0.5pct_alerts']:.3f} vs random {r['recall_at_0.5pct_alerts']:.3f}. "
          f"The two test sets contain different numbers of frauds ({M['time_split']['fraud']['test']} vs {M['random_split']['fraud']['test']}), so part of any gap is just a different test set. "
          "Compare the difference with the bootstrap intervals above before calling it real: test sets contain only tens of frauds."]
    if "control" in parts:
        c = parts["control"]["label_shuffle_time_split"]
        L += ["", "## Leakage control (labels shuffled in training)", "",
              f"Average precision on the true test labels: {c['mean_average_precision']:.4f} (per repeat {', '.join(f'{v:.4f}' for v in c['per_repeat'])}) vs test prevalence {c['test_prevalence']:.4f}. "
              "A value near the prevalence means the pipeline is not leaking labels; a clearly higher value would mean it is."]
    if "rolling" in parts:
        L += ["", "## Rolling origin (expanding window, XGBoost raw)", "", "| test block | train rows | test rows | frauds in test | average precision | recall @0.5% alerts |", "|---|---|---|---|---|---|"]
        for f in parts["rolling"]["rolling_origin"]:
            L.append(f"| {f['fold']} | {f['train_rows']:,} | {f['test_rows']:,} | {f['test_fraud']} | " + (f"{f['average_precision']:.3f} | {f['recall_at_0p5pct_alerts']:.3f} |" if "average_precision" in f else "n/a | n/a |"))
        L += ["", "Small fraud counts per block make single-block numbers noisy; look at the spread, not any one row."]
    L += ["", "## What each outcome would and would not mean", "",
          "- Calibration: if raw XGBoost has the lowest Brier / ECE here too, that REPEATS the Phase 1 finding on real data; if calibration helps, say so and explain the difference (real data, 0.17% prevalence, much more training data).",
          "- Time vs random: a small gap means this dataset cannot show ordering effects in two days; it does not show that ordering never matters.",
          "- XGBoost vs logistic regression: report the gap honestly; on PCA features a linear model can be strong.",
          "- Whatever the scores, this says nothing about the layered system, the graph stage, the GenAI-era families or the simulator's realism.", "",
          "## Limits", "",
          "- About two days of data; no card / customer id (customer-grouped splits impossible); PCA-anonymised features; tens of frauds per block; bootstrap over rows ignores dependence.",
          "- Hyper-parameters are the project's Stage 2 settings, not tuned for this data; `tree_method=hist` instead of `exact` for speed.", ""]
    (OUT / "phase8_report.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote", OUT / "phase8_report.md")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", required=True, choices=["main", "control", "rolling", "report"])
    ap.add_argument("--csv", default=str(ROOT / "data" / "public" / "creditcard.csv"))
    ap.add_argument("--boot", type=int, default=200)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default=None, help="output folder (default reports/public)")
    a = ap.parse_args()
    if a.out:
        OUT = Path(a.out)
    {"main": stage_main, "control": stage_control, "rolling": stage_rolling, "report": stage_report}[a.stage](a)
