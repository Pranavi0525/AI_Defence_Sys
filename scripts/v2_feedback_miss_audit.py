#!/usr/bin/env python3
"""
scripts/v2_feedback_miss_audit.py -- Phase 7b: what kind of fraud does the round-0 model miss (out-of-fold, training part only)?

    cmd:  set PYTHONPATH=src
          python scripts/v2_feedback_miss_audit.py
Writes reports/v2/feedback_miss_audit.md. Uses the same worlds / splits / pipeline as the feedback loop (repetitions 0-3).
"""
import sys, warnings
from pathlib import Path
warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "src"))

import pandas as pd                                  # noqa: E402
from v2.evalkit import folds_for                     # noqa: E402
from v2.features import WORLD_B_HARD, build_world_b  # noqa: E402
from v2.feedback import Pipeline                     # noqa: E402

REPS = 4


def md_table(df):
    cols = [df.index.name or ""] + list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        out.append("| " + " | ".join([str(idx)] + [f"{v:.3f}" if ("rate" in c or "share" in c) else str(int(v)) for c, v in zip(df.columns, row)]) + " |")
    return "\n".join(out)


def main():
    rows = []
    for rep in range(REPS):
        df, recs = build_world_b(seed=2026 + 101 * rep, return_records=True, **WORLD_B_HARD)
        diff = {r["trace_id"]: r["attack_difficulty"] for r in recs}
        tr, _ = folds_for(df, 11 + rep, n=4)[0]
        T = df.iloc[tr].reset_index(drop=True)
        p = Pipeline(seed=11 + rep).fit(T)
        T["difficulty"], T["decision"] = T.trace_id.map(diff), p.oof_decision
        rows.append(T[T.fraud == 1][["family", "difficulty", "decision"]])
    f = pd.concat(rows)
    by = f.groupby("difficulty").apply(lambda g: pd.Series({"fraud_traces": len(g), "missed_(ALLOW)": int((g.decision == 0).sum())}))
    by["miss_rate"] = by["missed_(ALLOW)"] / by["fraud_traces"]
    by["share_of_all_misses"] = by["missed_(ALLOW)"] / by["missed_(ALLOW)"].sum()
    fam = f.groupby("family").apply(lambda g: pd.Series({"fraud_traces": len(g), "missed_(ALLOW)": int((g.decision == 0).sum())}))
    fam["miss_rate"] = fam["missed_(ALLOW)"] / fam["fraud_traces"]
    md = ["# Feedback loop: what does the round-0 model miss? (generated by scripts/v2_feedback_miss_audit.py)", "",
          f"Out-of-fold decisions on the training part of {REPS} synthetic worlds (same worlds and splits as feedback-loop repetitions 0-{REPS - 1}).",
          "`difficulty` is the generator's own label: `stealth` = the attacker adapted to look legitimate; `plain` = it did not.", "",
          md_table(by), "", md_table(fam), ""]
    out = ROOT / "reports" / "v2" / "feedback_miss_audit.md"
    out.write_text("\n".join(md), encoding="utf-8")
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
