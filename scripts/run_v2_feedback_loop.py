#!/usr/bin/env python3
"""
scripts/run_v2_feedback_loop.py -- Phase 7b: analyst feedback loop, honest before/after.

    cmd:  set PYTHONPATH=src
          python scripts/run_v2_feedback_loop.py --reps 10 --per-case 2 --found-share 1.0
          python scripts/run_v2_feedback_loop.py --reps 10 --per-case 2 --found-share 0.5
          python scripts/run_v2_feedback_loop.py --reps 10 --per-case 4 --found-share 1.0
          python scripts/run_v2_feedback_loop.py --report

Each run takes about 10 s per repetition and writes reports/v2/feedback_loop_<config>.json.
--report reads every such file and writes reports/v2/feedback_loop.md (every number is generated, none typed by hand).
"""
import argparse, json, sys, time, warnings
from pathlib import Path
warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "src"))

from v2.feedback import run_rep, summarise  # noqa: E402

OUT = ROOT / "reports" / "v2"
HEADLINE = ["recall_flag", "recall_block", "legit_flag_rate", "legit_block_rate", "precision_flagged_at_0.6pct", "cost_per_10k"]


def tag(per_case, found_share):
    return f"pc{per_case}_found{int(round(found_share * 100))}"


def run(args):
    t0 = time.time()
    reps = []
    for r in range(args.reps):
        reps.append(run_rep(r, per_case=args.per_case, found_share=args.found_share))
        print(f"rep {r + 1}/{args.reps} done ({time.time() - t0:.0f}s)", flush=True)
    doc = {"config": {"reps": args.reps, "per_case": args.per_case, "found_share": args.found_share}, "reps": reps, "summary": summarise(reps)}
    OUT.mkdir(parents=True, exist_ok=True)
    p = OUT / f"feedback_loop_{tag(args.per_case, args.found_share)}.json"
    p.write_text(json.dumps(doc, indent=1), encoding="utf-8")
    print("wrote", p)


def fmt(k, v):
    return f"{v:,.0f}" if k == "cost_per_10k" else f"{v:.3f}"


def report():
    files = sorted(OUT.glob("feedback_loop_*.json"))
    if not files:
        sys.exit("no feedback_loop_*.json found; run the loop first")
    L = ["# v2 analyst feedback loop (generated by scripts/run_v2_feedback_loop.py)", "",
         "SYNTHETIC World B. For each repetition: new world, held-out customer-grouped test quarter, round-0 model, analyst queue from "
         "OUT-OF-FOLD training decisions, fresh look-alike cases, retrain. `control_same_size` adds the same NUMBER of fresh fraud/legit "
         "traces from the ordinary mix, so `targeted - control` isolates the value of learning from mistakes (vs. just more data).", ""]
    for f in files:
        d = json.loads(f.read_text(encoding="utf-8"))
        c, S = d["config"], d["summary"]
        q = [r["queue"] for r in d["reps"]]
        nf = [r["n_fresh"] for r in d["reps"]]
        L += [f"## Config: {c['reps']} repetitions, {c['per_case']} fresh cases per mistake, {int(c['found_share'] * 100)}% of misses found by analysts", "",
              f"Average per repetition: {sum(x['n_missed_total'] for x in q) / len(q):.0f} misses ({sum(x['n_misses_found'] for x in q) / len(q):.0f} found), "
              f"{sum(x['n_false_alarms'] for x in q) / len(q):.0f} false alarms; fresh traces added: "
              f"{sum(x['targeted_fraud'] for x in nf) / len(nf):.0f} fraud + {sum(x['targeted_legit'] for x in nf) / len(nf):.0f} legit.", "",
              "| metric (test set, mean over reps) | baseline | targeted | control (same size) | targeted - baseline (mean, sd, up/down) | targeted - control (mean, sd, up/down) |",
              "|---|---|---|---|---|---|"]
        for k in HEADLINE:
            row = [fmt(k, S["arms"][n][k]) for n in ("baseline", "targeted", "control_same_size")]
            pb, pc = S["paired"]["targeted_minus_baseline"][k], S["paired"]["targeted_minus_control_same_size"][k]
            cell = lambda p: f"{p['mean']:+,.3f} (sd {p['sd']:.3f}, {p['n_up']}/{p['n_down']})" if k != "cost_per_10k" else f"{p['mean']:+,.0f} (sd {p['sd']:,.0f}, {p['n_up']}/{p['n_down']})"
            L.append(f"| {k} | {row[0]} | {row[1]} | {row[2]} | {cell(pb)} | {cell(pc)} |")
        L += ["", "Per-family recall (REVIEW+BLOCK) and legit flag rate by kind, mean over reps:", "",
              "| item | baseline | targeted | control |", "|---|---|---|---|"]
        for k in sorted(k for k in S["arms"]["baseline"] if k.startswith(("recall_SYN", "recall_FAKE", "recall_DEEP", "recall_AI", "flag_"))):
            L.append(f"| {k} | " + " | ".join(f"{S['arms'][n][k]:.3f}" for n in ("baseline", "targeted", "control_same_size")) + " |")
        thr = {n: [r["arms"][n]["t_review"] for r in d["reps"]] for n in ("baseline", "targeted", "control_same_size")}
        L += ["", "Learned review threshold per repetition (shows how unstable the policy is on ~1,000 training rows): "
              + "; ".join(f"{n}: min {min(v):.2f}, max {max(v):.2f}" for n, v in thr.items()), ""]
    L += ["## How to read this honestly", "",
          "- `up/down` = in how many repetitions the difference was positive / negative. Lower is better for legit_flag_rate, legit_block_rate and cost_per_10k; higher is better for recall and precision.",
          "- Fresh cases come from the SAME generator as the test set: any gain is an in-distribution best case, not evidence about unseen fraud or real analysts.",
          "- Judge the loop by `targeted - control`, not `targeted - baseline`: the second one also contains the effect of simply having more training data.",
          "- If an sd is as large as the mean difference, there is no detectable effect with this many repetitions.", ""]
    (OUT / "feedback_loop.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote", OUT / "feedback_loop.md")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=10)
    ap.add_argument("--per-case", type=int, default=2)
    ap.add_argument("--found-share", type=float, default=1.0)
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    report() if a.report else run(a)
