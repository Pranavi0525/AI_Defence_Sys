#!/usr/bin/env python3
"""
scripts/make_v2_dossiers.py -- Phase 7a: writes reports/v2/dossiers.md with example case dossiers.

    cmd:  set PYTHONPATH=src
          python scripts/make_v2_dossiers.py

Cases come from a FRESH synthetic World B (seed 777, never used for training the served model), scored by the served bundle in models/v2/.
The label is known here because it is a test script; the API does not know it. Picks: one flagged case per fraud family, one legitimate
case that was flagged (false alarm), one fraud that was ALLOWed (miss). Selection is "first of each kind in generation order", not cherry-picked.
"""
import sys, warnings
from collections import Counter
from pathlib import Path
warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "src"))

from v2.dossier import build_dossier, render_markdown      # noqa: E402
from v2.features import WORLD_B_HARD, build_world_b         # noqa: E402
from v2.serving.scorer import V2Scorer                      # noqa: E402

SEED = 777


def main():
    df, recs = build_world_b(seed=SEED, return_records=True, **WORLD_B_HARD)
    scorer = V2Scorer(ROOT / "models" / "v2")
    results = [(r, scorer.score(r)["decision"]) for r in recs]
    tally = Counter((r["attack_family"] if r["fraud"] else "legitimate", d) for r, d in results)
    picks, seen = [], set()
    for r, d in results:
        if r["fraud"] and d != "ALLOW" and ("flagged", r["attack_family"]) not in seen:
            seen.add(("flagged", r["attack_family"])); picks.append((f"FRAUD ({r['attack_family']}) correctly flagged", r))
    for r, d in results:
        if not r["fraud"] and d != "ALLOW":
            picks.append((f"LEGITIMATE ({r['attack_family']}) wrongly flagged -- a false alarm", r)); break
    for r, d in results:
        if r["fraud"] and d == "ALLOW":
            picks.append((f"FRAUD ({r['attack_family']}) that slipped through as ALLOW -- a miss", r)); break
    L = ["# v2 example case dossiers (generated by scripts/make_v2_dossiers.py)", "",
         f"Fresh SYNTHETIC World B, seed {SEED}, served model {scorer.model_version}. Decision counts on this world (family, decision): "
         + ", ".join(f"{k[0]}/{k[1]}={v}" for k, v in sorted(tally.items())), "",
         "The truth label below each title is known only because this is a test script. The acting-party block uses the true family; in production it would stay empty until an analyst triages the case.", ""]
    for title, r in picks:
        fam = r["attack_family"] if r["fraud"] else None
        d = build_dossier(scorer, r, family=fam, include_allow=True)
        L += [f"# {title}", "", render_markdown(d), "---", ""]
    out = ROOT / "reports" / "v2" / "dossiers.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("wrote", out, "with", len(picks), "dossiers")


if __name__ == "__main__":
    main()
