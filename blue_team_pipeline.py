# Step 4 - Assemble the training table
# ---------------------------------------------------------------------------
def add_hesitation_delta(df: pd.DataFrame) -> pd.DataFrame:
    """HESITATION_DELTA -- a synthetic, honestly-labeled proxy for the
    "duress pause" signal real APP-fraud systems chase, built entirely
    from timestamps this pipeline already logs (NOT a claim of real
    keystroke/mouse biometrics, which this system has no sensors to
    observe).

    Raw signal: time_from_beneficiary_add_to_transaction (already
    extracted per-trace). This is normalized -- z-scored -- against
    each customer's OWN historical transaction pace
    (mean_time_between_transactions across that customer's other
    traces in this dataset), so a naturally slow/careful customer and
    a naturally fast one aren't judged on the same absolute clock.

    Honest fallbacks (documented, not silently defaulted):
      - No beneficiary-add event occurred in this trace at all ->
        neutral 0.0 (no opinion, not a guess).
      - Customer has only a single trace in the dataset (no history to
        build a per-customer baseline from -- a cold-start account) ->
        fall back to the population-wide baseline instead of dividing
        by a zero/undefined standard deviation.
    """
    df = df.copy()
    df["HESITATION_DELTA"] = 0.0

    grouped = df.groupby("customer_id")["mean_time_between_transactions"]
    baseline_mean = grouped.transform("mean")
    baseline_std = grouped.transform("std").fillna(0.0)

    global_mean = df["mean_time_between_transactions"].mean()
    global_std = df["mean_time_between_transactions"].std()
    if not global_std or np.isnan(global_std):
        global_std = 1.0

    cold_start = baseline_std <= 1e-6
    effective_mean = baseline_mean.where(~cold_start, global_mean)
    effective_std = baseline_std.where(~cold_start, global_std)
    effective_std = effective_std.replace(0.0, global_std)

    has_beneficiary = df["beneficiary_added_before_transaction"] == 1
    z = (df["time_from_beneficiary_add_to_transaction"] - effective_mean) / effective_std
    df.loc[has_beneficiary, "HESITATION_DELTA"] = z[has_beneficiary]
    # rows with no beneficiary-add event keep the neutral 0.0 set above

    return df


