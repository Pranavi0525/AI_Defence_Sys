    repo_root = cfg["REPO_ROOT"]

    print("Loading Red Team attack corpora...")
    ato_records = load_attack_corpus(repo_root / cfg["ATO_CORPUS_PATH"], "ATO")
    app_records = load_attack_corpus(repo_root / cfg["APP_CORPUS_PATH"], "APP")

    mule_path = repo_root / cfg["MULE_CORPUS_PATH"]
    if mule_path.exists():
        mule_records = load_attack_corpus(mule_path, "MULE_NETWORK")
    else:
        # Not a hard failure -- lets the pipeline still run against just
        # ATO/APP if reports/mule_corpus_raw.json hasn't been generated yet
        # (see scripts/run_mule_network_qualification.py).
        print(f"  WARNING: {mule_path.name} not found, skipping MULE_NETWORK "
              f"traces. Run scripts/run_mule_network_qualification.py first "
              f"to include them.")
        mule_records = []

    print("Building legitimate population (session-windowed)...")
    legit_records = build_legitimate_traces(cfg)

    all_records = ato_records + app_records + mule_records + legit_records
    print(f"Total traces: {len(all_records)} "
          f"({len(ato_records)} ATO + {len(app_records)} APP + "
          f"{len(mule_records)} MULE_NETWORK + {len(legit_records)} legit)")

    print("Extracting features...")
    rows = []
    for rec in all_records:
        feats = extract_features(rec)
        feats["fraud"] = rec["fraud"]
        feats["attack_family"] = rec["attack_family"]
        feats["attack_difficulty"] = rec["attack_difficulty"]
        feats["customer_id"] = rec["customer_id"]
        rows.append(feats)

    df = pd.DataFrame(rows)
    print("Computing HESITATION_DELTA (per-customer pacing baseline)...")
    df = add_hesitation_delta(df)
    return df


